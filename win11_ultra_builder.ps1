foreach ($k in $labConfigKeys) {
    & reg.exe add "HKLM\zSYSTEM\Setup\LabConfig" /v $k /t REG_DWORD /d 1 /f 2>$null | Out-Null
}

# 稳健卸载注册表并提交 WinPE 映像更改
Safely-UnloadHive "HKLM\zSYSTEM" | Out-Null
